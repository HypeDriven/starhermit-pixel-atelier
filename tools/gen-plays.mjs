// Writes the generated play scripts (tests/native/*.play) from the rules and
// content: Journey stage 1 solved by keys on a desktop (swatch number keys, the
// region tool, the keyboard cursor and Enter), and the four Learn lessons by
// finger on a DPR-3 phone (swatches by name, tools in the side drawer, cells
// touched at their projected centres — render.ts's camera fit and framing
// computed here — a swipe for the drag lesson, zoom, hint and refit for the
// camera lesson). Run after content or camera changes: node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { JOURNEY, LESSONS, lessonContent } from '../js/content.js';
import { Session } from '../js/session.js';
import * as rules from '../js/rules.js';

const out = (name, lines) => writeFileSync(new URL(`../tests/native/${name}`, import.meta.url), lines.join('\n') + '\n');

import { projector, safeOnPhone, regions, fmt } from './plans.mjs';

// ---------------------------------------------------------------- Journey stage 1 by keys (desktop)
{
  const stage = JOURNEY[0];
  const s = new Session(stage);
  s.start();
  const L = [
    '# Generated by tools/gen-plays.mjs: Journey stage 1 (First Sprout) on a desktop (1280 x 800) by keys: number keys pick',
    '# swatches, R the region tool, the arrows move the keyboard cursor and Enter floods each region; then the results.',
    '# viewport 1280x800@1',
    'until 600 Paint the table',
    'frames 10',
    'click =Play',
    'until 120 Journey stage',
    'frames 10',
    'save j1-setup',
    'click =Start',
    'until 600 0:00',
    'frames 30',
    'key KeyR 1',
    'frames 3',
  ];
  let kc = -1;
  for (const reg of regions(s.state)) {
    if (s.state.filled[reg.cells[0]]) continue;
    L.push(`key Digit${reg.color} 1`, 'frames 2');
    s.select(reg.color);
    const target = reg.cells[0];
    if (kc < 0) {
      L.push('key ArrowRight 1', 'frames 1');
      const la = rules.legalActions(s.state);
      kc = la.colors.find((c) => c.color === s.state.selected)?.sample ?? la.colors[0]?.sample ?? 0;
    }
    const w = s.state.w;
    let dx = (target % w) - (kc % w), dy = Math.floor(target / w) - Math.floor(kc / w);
    while (dx) { L.push(`key Arrow${dx > 0 ? 'Right' : 'Left'} 1`, 'frames 1'); dx -= Math.sign(dx); }
    while (dy) { L.push(`key Arrow${dy > 0 ? 'Down' : 'Up'} 1`, 'frames 1'); dy -= Math.sign(dy); }
    kc = target;
    L.push('key Enter 1', 'frames 3');
    const r = s.fill(target, reg.color, 'region');
    if (!r.ok) throw new Error(`journey region fill failed: ${r.reason}`);
    if (L.filter((l) => l.startsWith('key Enter')).length === 3) L.push('save j1-play');
  }
  if (s.state.status !== 'complete') throw new Error('journey plan did not complete');
  L.push('# simulated: complete', 'until 300 Total', 'frames 20', 'expect Canvas complete!', 'expect Next stage', 'expect Total', 'save j1-results', 'click =Home', 'until 120 Paint the table', 'expect 1 / 42 stages');
  out('journey-keys.play', L);
}

// ---------------------------------------------------------------- the four lessons by finger (phone)
{
  const W = 390, H = 844;
  const L = [
    '# Generated by tools/gen-plays.mjs: the four Learn lessons on a phone (390 x 844, DPR 3) by finger: swatches by name,',
    '# the tools from the side drawer, cells touched at their projected centres (region floods), a swipe for the drag',
    '# lesson, zoom / hint / refit for the camera lesson; each to its results and on to the next.',
    `# viewport ${W}x${H}@3`,
    'until 600 Paint the table',
    'frames 10',
    'touch =Learn',
    'until 120 Atelier Lessons',
    'frames 10',
    'touch =1. Color & Fill',
  ];
  const swatch = (c, n) => (c === 0 ? `touch Color background,` : `touch Color ${c},`) + (n ? '' : '');
  const drawerTool = (name) => ['touch =◨', 'frames 15', `touch =${name}`, 'frames 10'];
  const pickSafe = (proj, cells) => cells.map((c) => proj(c)).find((p) => safeOnPhone(p, W, H));
  LESSONS.forEach((lesson, li) => {
    const { content } = lessonContent(lesson.id);
    const s = new Session(content);
    s.start();
    const proj = projector(W, H, content.width, content.height);
    L.push(`# ${lesson.id} ${lesson.title}`, 'until 600 0:00', 'frames 40');
    if (li === 0) L.push('save lesson-1');
    const steps = lesson.steps.map((st) => st.require.type);
    let tool = 'brush';
    if (steps.includes('stroke')) {
      // a run of ≥ 4 same-color cells in a row, swiped with the brush
      const w = content.width;
      let best = null;
      for (let y = 0; y < content.height && !best; y++) {
        for (let x = 0; x + 4 <= w && !best; x++) {
          const c0 = content.targets[y * w + x];
          if (c0 === 0) continue;
          let n = 1;
          while (x + n < w && content.targets[y * w + x + n] === c0) n++;
          if (n >= 4) {
            const a = proj(y * w + x), b = proj(y * w + x + n - 1);
            if (safeOnPhone(a, W, H) && safeOnPhone(b, W, H)) best = { color: c0, cells: Array.from({ length: n }, (_, k) => y * w + x + k), a, b };
          }
        }
      }
      if (!best) throw new Error('no swipe run in ' + lesson.id);
      L.push(swatch(best.color), 'frames 8', `swipe ${fmt(best.a.x)} ${fmt(best.a.y)} ${fmt(best.b.x)} ${fmt(best.b.y)} 12`, 'frames 10');
      s.select(best.color);
      for (const c of best.cells) s.fill(c, best.color, 'brush', 'x', c !== best.cells[0]);
      L.push('expect Step 2/2');
    }
    if (steps.includes('camera')) {
      L.push(...drawerTool('Zoom in'), 'frames 30', 'expect Step 2/3');
      L.push(...drawerTool('Hint'), 'frames 10', 'expect Step 3/3');
      s.hint();
      L.push(...drawerTool('Fit'), 'frames 180');
    }
    // the rest by region floods (lesson 1 selects color 1 first: its first step)
    const order = regions(s.state);
    if (steps[0] === 'select') order.sort((a, b) => (a.color === 1 ? -1 : 0) - (b.color === 1 ? -1 : 0));
    let current = -1;
    for (const reg of order) {
      if (s.state.filled[reg.cells[0]]) continue;
      if (reg.color !== current) { L.push(swatch(reg.color), 'frames 8'); s.select(reg.color); current = reg.color; }
      if (tool !== 'region') { L.push(...drawerTool('Region')); tool = 'region'; }
      const p = pickSafe(proj, reg.cells);
      if (!p) throw new Error(`no safe cell in a region of ${lesson.id}`);
      L.push(`touch ${fmt(p.x)} ${fmt(p.y)}`, 'frames 8');
      const r = s.fill(reg.cells[0], reg.color, 'region');
      if (!r.ok) throw new Error(`${lesson.id}: ${r.reason}`);
    }
    if (s.state.status !== 'complete') throw new Error(`${lesson.id} plan did not complete`);
    L.push('# simulated: complete', 'until 300 Total', 'frames 20', 'expect Canvas complete!', `save lesson-${li + 1}-results`);
    if (li + 1 < LESSONS.length) L.push('touch =Next lesson');
  });
  L.push('expect Retry');
  out('lessons-phone.play', L);
}
console.log('wrote tests/native/journey-keys.play, lessons-phone.play');
